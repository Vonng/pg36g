    repeat(md5(('product-' || g)::text), 2)
FROM generate_series(1::bigint, :product_count::bigint) AS g;

INSERT INTO shopbench.inventory (product_id, quantity, updated_at)
SELECT
    product_id,
    (1000000 + product_id % 1000)::integer,
    timestamptz '2026-01-01 00:00:00+00'
FROM shopbench.product;

INSERT INTO shopbench.order_history (
    order_id,
    customer_id,
    product_id,
    quantity,
    amount_cents,
    status,
    placed_at,
    payload
)
SELECT
    g,
    ((g * 7919) % :customer_count) + 1,
    ((g * 1543) % :product_count) + 1,
    ((g % 3) + 1)::smallint,
    (
        (500 + (((g * 1543) % :product_count) + 1) % 50000)
        * ((g % 3) + 1)
    )::integer,
    CASE g % 20
        WHEN 0 THEN 'refunded'
        WHEN 1 THEN 'cancelled'
        ELSE 'fulfilled'
    END,
    timestamptz '2026-01-01 00:00:00+00'
        - ((g % 7776000)::double precision * interval '1 second'),
    repeat(md5(('order-' || g)::text), 2)
FROM generate_series(1::bigint, :history_count::bigint) AS g;

ANALYZE shopbench.customer;
ANALYZE shopbench.product;
ANALYZE shopbench.inventory;
ANALYZE shopbench.order_history;
ANALYZE shopbench.order_live;

SELECT jsonb_build_object(
    'scale_factor', :scale_factor::bigint,
    'customers', (SELECT count(*) FROM shopbench.customer),
    'products', (SELECT count(*) FROM shopbench.product),
    'historical_orders', (SELECT count(*) FROM shopbench.order_history),
    'database_bytes', pg_database_size(current_database()),
    'schema_bytes', (
        SELECT sum(pg_total_relation_size(c.oid))
        FROM pg_class AS c
        JOIN pg_namespace AS n
          ON n.oid = c.relnamespace
        WHERE n.nspname = 'shopbench'
          AND c.relkind IN ('r', 'p', 'm')
    )
) AS initialized;
